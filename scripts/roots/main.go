// Command roots rebuilds internal/roots/roots.pem, the root list of the
// node's own outbound TLS (docs/08-decisions.md, R4-41), from two PEM
// files: Chrome's list and Mozilla's as the client's core embeds them,
// both without the CAs CCADB places in China. The result is their
// intersection by the SHA-256 of the DER SubjectPublicKeyInfo, each root
// as the Chrome list has it, in that list's order.
//
// It reads files only, nothing from the network. The inputs may be the
// core's generated Go files (common/certificate/chrome.go, mozilla.go):
// PEM blocks are found anywhere in a file. The list of 2026-11-14, from a
// checkout of the core at SING_BOX:
//
//	go run ./scripts/roots \
//	    -chrome $SING_BOX/common/certificate/chrome.go -mozilla $SING_BOX/common/certificate/mozilla.go \
//	    -source 'arngory/sing-box 34eaa8c9c5a95702fec275561e9292a8f7ed9a08, common/certificate/chrome.go and mozilla.go (cmd/internal/update_certificates)' \
//	    -date 2026-11-14 -o internal/roots/roots.pem
//
// internal/roots TestEmbedded then checks the count, the roots the
// node's peers chain to, and the file's SHA-256 (embeddedSHA256): update
// all three when the list changes, the hash to `sha256sum
// internal/roots/roots.pem` of the file this wrote, in the same commit.
package main

import (
	"bytes"
	"crypto/sha256"
	"crypto/x509"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"flag"
	"fmt"
	"os"
	"regexp"
	"strings"
)

func main() {
	chrome := flag.String("chrome", "", "Chrome's list, PEM")
	mozilla := flag.String("mozilla", "", "Mozilla's list, PEM")
	source := flag.String("source", "", "where the two lists come from (repository, commit, files), for the header")
	date := flag.String("date", "", "the date of the lists, YYYY-MM-DD, for the header")
	out := flag.String("o", "", "output file (stdout when empty)")
	flag.Parse()
	if *chrome == "" || *mozilla == "" || *source == "" || !dateRe.MatchString(*date) {
		flag.Usage()
		os.Exit(2)
	}
	if err := run(*chrome, *mozilla, *source, *date, *out); err != nil {
		fmt.Fprintln(os.Stderr, "roots:", err)
		os.Exit(1)
	}
}

var dateRe = regexp.MustCompile(`^\d{4}-\d{2}-\d{2}$`)

func run(chromeFile, mozillaFile, source, date, out string) error {
	cb, err := os.ReadFile(chromeFile) //nolint:gosec // G304: the operator's file
	if err != nil {
		return err
	}
	mb, err := os.ReadFile(mozillaFile) //nolint:gosec // G304: the operator's file
	if err != nil {
		return err
	}
	chrome, err := parse(cb)
	if err != nil {
		return fmt.Errorf("%s: %w", chromeFile, err)
	}
	mozilla, err := parse(mb)
	if err != nil {
		return fmt.Errorf("%s: %w", mozillaFile, err)
	}
	b := Intersect(chrome, mozilla, Header{Source: source, Date: date, Chrome: len(chrome), Mozilla: len(mozilla)})
	if out == "" {
		_, err = os.Stdout.Write(b)
		return err
	}
	return os.WriteFile(out, b, 0o644) //nolint:gosec // G306: a source file
}

// parse reads every CERTIFICATE block of a file, whatever is around them.
func parse(b []byte) ([]*x509.Certificate, error) {
	var out []*x509.Certificate
	for {
		var blk *pem.Block
		blk, b = pem.Decode(b)
		if blk == nil {
			break
		}
		if blk.Type != "CERTIFICATE" {
			continue
		}
		c, err := x509.ParseCertificate(blk.Bytes)
		if err != nil {
			return nil, err
		}
		out = append(out, c)
	}
	if len(out) == 0 {
		return nil, errors.New("no certificates")
	}
	return out, nil
}

// Header is what the output's header says.
type Header struct {
	Source          string
	Date            string
	Chrome, Mozilla int
}

// SPKI is the hex SHA-256 of a certificate's DER SubjectPublicKeyInfo.
func SPKI(c *x509.Certificate) string {
	s := sha256.Sum256(c.RawSubjectPublicKeyInfo)
	return hex.EncodeToString(s[:])
}

// Intersect is the output file: the roots of chrome whose key mozilla has
// too, once each, in chrome's order.
func Intersect(chrome, mozilla []*x509.Certificate, h Header) []byte {
	inMozilla := map[string]bool{}
	for _, c := range mozilla {
		inMozilla[SPKI(c)] = true
	}
	seen := map[string]bool{}
	var keep []*x509.Certificate
	for _, c := range chrome {
		k := SPKI(c)
		if inMozilla[k] && !seen[k] {
			seen[k] = true
			keep = append(keep, c)
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, `# The root list of the node's own outbound TLS (internal/roots).
# Generated by scripts/roots. DO NOT EDIT.
#
# source: %s
# date: %s
# count: %d
#
# The intersection of Chrome's list (%d roots) and Mozilla's (%d) as the
# client's core embeds them: both from CCADB, without the CAs whose country
# or geographic focus is China. A root is in both when the SHA-256 of its
# DER SubjectPublicKeyInfo is; the certificate is the Chrome list's.
# GPL-3.0, as the core and this repository.
`, oneLine(h.Source), h.Date, len(keep), h.Chrome, h.Mozilla)
	for _, c := range keep {
		fmt.Fprintf(&b, "\n# %s\n# spki-sha256 %s\n", oneLine(c.Subject.String()), SPKI(c))
		_ = pem.Encode(&b, &pem.Block{Type: "CERTIFICATE", Bytes: c.Raw})
	}
	return b.Bytes()
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
