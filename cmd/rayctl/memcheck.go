// memoryHost is what memoryResults reads (tests give their own).
type memoryHost struct {
	total      func() int64                   // the host's memory (MemTotal), 0 when not known
	units      func() []string                // the installed units with a memory limit
	show       func(unit, prop string) string // systemctl show -p prop --value unit
	cgroupRoot string                         // where cgroup v2 is mounted
}

var defaultMemoryHost = memoryHost{
	total: func() int64 { return memlimit.Read(memlimit.System).MemTotal },
	units: func() []string {
		var out []string
		files, _ := filepath.Glob("/etc/systemd/system/*.service")
		for _, f := range files {
			b, err := os.ReadFile(f) //nolint:gosec // G304: a unit of /etc/systemd/system
			if err == nil && strings.Contains(string(b), "\nMemoryMax=") && strings.HasPrefix(string(b), "# Generated by raycontrol") {
				out = append(out, filepath.Base(f))
			}
		}
		return out
	},
	show: func(unit, prop string) string {
		out, _ := exec.Command("systemctl", "show", "-p", prop, "--value", unit).Output() //nolint:gosec // G204: a unit raycontrol wrote, a fixed property
		return strings.TrimSpace(string(out))
	},
	cgroupRoot: "/sys/fs/cgroup",
}

// memoryResults are the node's memory as raycontrol sizes it
// (docs/spec/memory-v1.md §1, §4): the budget of this host and its shares;
// whether the kernel holds each unit to its limit (in a container without
// a delegated memory controller, or on cgroup v1, systemd sets nothing);
// whether the data plane already runs at its high mark, where the kernel
// throttles it: the services together want more than the host has.
func memoryResults(h memoryHost) []hostcheck.Result {
	m := deploy.MemoryOf(h.total())
	if m.Total == 0 {
		return nil
	}
	mib := func(n int64) int64 { return n >> 20 }
	budget := hostcheck.Result{Level: hostcheck.Advised, Name: "memory budget", OK: true,
		Detail: fmt.Sprintf("%d MiB of %d for raycontrol: rayd %d, rayspa %d, the data plane %d (each of its units up to %d)",
			mib(m.Budget), mib(m.Total), mib(m.Rayd), mib(m.Rayspa), mib(m.Slice), mib(m.Unit))}
	if m.Budget-m.Rayd-m.Rayspa < m.Slice {
		budget.OK = false
		budget.Detail += ": the data plane gets its least, more than the budget leaves it"
		budget.Fix = "a host with more memory"
	}
	out := []hostcheck.Result{budget}
	units := h.units()
	if len(units) == 0 {
		return out
	}
	var unlimited []string
	checked := 0
	for _, u := range units {
		if h.show(u, "ActiveState") != "active" {
			continue
		}
		want := h.show(u, "MemoryMax")
		cg := h.show(u, "ControlGroup")
		if want == "" || want == "infinity" || cg == "" {
			continue
		}
		checked++
		got, err := os.ReadFile(path.Join(h.cgroupRoot, cg, "memory.max")) //nolint:gosec // G304: the unit's cgroup
		if err != nil || !sameLimit(strings.TrimSpace(string(got)), want) {
			unlimited = append(unlimited, u)
		}
	}
	switch {
	case checked == 0:
	case len(unlimited) > 0:
		out = append(out, hostcheck.Result{Level: hostcheck.Advised, Name: "memory limits", OK: false,
			Detail: fmt.Sprintf("the kernel does not hold %s to its limit (no memory controller for systemd here: a container, or cgroup v1); "+
				"a unit can take the host's memory, and the kernel's OOM killer then picks by score alone", strings.Join(unlimited, ", ")),
			Fix: "run the node on a VM, or give the container a memory controller (cgroup v2, delegated)"})
	default:
		out = append(out, hostcheck.Result{Level: hostcheck.Advised, Name: "memory limits", OK: true,
			Detail: fmt.Sprintf("the kernel holds the %d running units with a limit to it", checked)})
	}
	slice := strings.TrimSuffix(h.show(deploy.DataSlice, "ControlGroup"), "/")
	if slice == "" {
		return out
	}
	read := func(f string) int64 {
		b, err := os.ReadFile(path.Join(h.cgroupRoot, slice, f)) //nolint:gosec // G304: the data slice's cgroup
		if err != nil {
			return 0
		}
		n, _ := strconv.ParseInt(strings.TrimSpace(string(b)), 10, 64)
		return n
	}
	if cur, high := read("memory.current"), read("memory.high"); high > 0 && cur >= high {
		out = append(out, hostcheck.Result{Level: hostcheck.Advised, Name: "data plane memory", OK: false,
			Detail: fmt.Sprintf("the data plane uses %d MiB, at its high mark %d MiB: the kernel throttles it, and its services "+
				"together want more than this host gives them", mib(cur), mib(high)),
			Fix: "a host with more memory, or fewer services on this one"})
	}
	return out
}

// sameLimit reports whether the kernel's memory.max is the limit systemd
// set, both in bytes: the kernel keeps it in pages, so within one page
// (64 KiB, the largest).
func sameLimit(kernel, systemd string) bool {
	k, err1 := strconv.ParseInt(kernel, 10, 64)
	s, err2 := strconv.ParseInt(systemd, 10, 64)
	if err1 != nil || err2 != nil {
		return false
	}
	d := k - s
	return d > -64<<10 && d < 64<<10
}
