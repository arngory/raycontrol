package deploy

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"
)

// The conntrack table and its times (spec/conn-limit-v1.md §6.1), on a node
// and on a relay host: every forwarded or proxied flow is an entry. apply
// writes ConntrackSysctl with only the keys it must raise (the size) or
// lower (the times) against the live value: a bigger size or a shorter time
// the administrator set stays as it is. A key raycontrol wrote before stays
// raycontrol's while the live value is still its value. The values before
// are journaled (recordSysctl) and uninstall puts them back.
const (
	ConntrackSysctl = "/etc/sysctl.d/90-raycontrol-conntrack.conf"
	// ModulesLoad loads nf_conntrack at boot before systemd-sysctl: without
	// it the keys are not there yet, and sysctl -e skips them silently.
	ModulesLoad = "/etc/modules-load.d/raycontrol.conf"

	ConntrackMaxKey     = "net.netfilter.nf_conntrack_max"
	ConntrackBucketsKey = "net.netfilter.nf_conntrack_buckets"
	SynSentKey          = "net.netfilter.nf_conntrack_tcp_timeout_syn_sent"
	FinWaitKey          = "net.netfilter.nf_conntrack_tcp_timeout_fin_wait"
	TimeWaitKey         = "net.netfilter.nf_conntrack_tcp_timeout_time_wait"

	// The table's size: MemTotal / 16 KiB, up to a power of two, within
	// these (512 MiB and 1 GiB: 65 536; 2 GiB: 131 072; 4 GiB: 262 144).
	conntrackMin = 65536
	conntrackMax = 262144
)

// conntrackTimes are the times raycontrol lowers, never raises (§6.1).
var conntrackTimes = []struct {
	key  string
	want uint64
}{{SynSentKey, 30}, {FinWaitKey, 30}, {TimeWaitKey, 60}}

// ConntrackSize is the table's size for a host with memTotal KiB of memory.
func ConntrackSize(memTotalKiB uint64) uint64 {
	m := (memTotalKiB + 15) / 16 // entries: MemTotal / 16 KiB, up
	size := uint64(1)
	for size < m && size < conntrackMax {
		size <<= 1
	}
	return min(max(size, conntrackMin), conntrackMax)
}

// ConntrackKey is one key of ConntrackSysctl.
type ConntrackKey struct {
	Key   string
	Value uint64
}

// ConntrackKeys are the keys apply writes for a size, given the live
// values (a key missing: unknown, not written) and those the file has
// (raycontrol's from before). The size is written when the live one is
// smaller, a time when the live one is longer; either also when the live
// value is the file's: raycontrol's still, it follows the memory. A size
// key not in writable cannot be changed here (a container): left out.
func ConntrackKeys(size uint64, live, file map[string]uint64, writable map[string]bool) []ConntrackKey {
	var out []ConntrackKey
	ours := func(key string) bool {
		v, ok := file[key]
		return ok && live[key] == v
	}
	for _, key := range []string{ConntrackMaxKey, ConntrackBucketsKey} {
		if v, ok := live[key]; ok && writable[key] && (v < size || ours(key)) {
			out = append(out, ConntrackKey{key, size})
		}
	}
	for _, t := range conntrackTimes {
		if v, ok := live[t.key]; ok && (v > t.want || ours(t.key)) {
			out = append(out, ConntrackKey{t.key, t.want})
		}
	}
	return out
}

// conntrackFile is ConntrackSysctl with keys.
func conntrackFile(keys []ConntrackKey) File {
	var b strings.Builder
	b.WriteString("# Generated by raycontrol (spec/conn-limit-v1.md §6.1): the conntrack table by memory, and\n" +
		"# shorter SYN_SENT, FIN_WAIT and TIME_WAIT. Only what rayctl apply raised (the size) or\n" +
		"# lowered (the times) against the value it found: a bigger size or a shorter time set\n" +
		"# elsewhere is left alone. Files that sort later win at boot; rayctl check warns then.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%s = %d\n", k.Key, k.Value)
	}
	return File{Path: ConntrackSysctl, Mode: 0o644, Content: []byte(b.String())}
}

// modulesFile is ModulesLoad.
var modulesFile = File{Path: ModulesLoad, Mode: 0o644, Content: []byte("# Generated by raycontrol (spec/conn-limit-v1.md §6.1): before systemd-sysctl,\n" +
	"# so that the conntrack keys of " + ConntrackSysctl + " are there at boot.\nnf_conntrack\n")}

// memTotal is MemTotal in KiB, 0 when it cannot be read.
func (h *Host) memTotal() uint64 {
	b, err := os.ReadFile(h.path("/proc/meminfo"))
	if err != nil {
		return 0
	}
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) >= 2 && f[0] == "MemTotal:" {
			v, _ := strconv.ParseUint(f[1], 10, 64)
			return v
		}
	}
	return 0
}

// fileKeys are the keys a sysctl file of raycontrol's sets.
func (h *Host) fileKeys(path string) map[string]uint64 {
	out := map[string]uint64{}
	b, err := os.ReadFile(h.path(path))
	if err != nil {
		return out
	}
	for _, line := range strings.Split(string(b), "\n") {
		key, val, ok := strings.Cut(line, "=")
		key = strings.TrimSpace(key)
		if !ok || key == "" || strings.HasPrefix(key, "#") {
			continue
		}
		if v, err := strconv.ParseUint(strings.TrimSpace(val), 10, 64); err == nil {
			out[key] = v
		}
	}
	return out
}

// Conntrack sizes the conntrack table and shortens its times
// (spec/conn-limit-v1.md §6.1): ModulesLoad, then ConntrackSysctl with the
// keys ConntrackKeys gives, loaded now. The values before are journaled
// for uninstall. It warns, and goes on, where a key cannot be read or set:
// a container may not let the size change (only the initial network
// namespace has it), and says the numbers that hold there.
func (h *Host) Conntrack() {
	changed, err := h.WriteFile(modulesFile)
	if err != nil {
		fmt.Fprintf(h.Out, "warning: %s cannot be written: %v\n", ModulesLoad, err)
	} else if changed {
		fmt.Fprintln(h.Out, "wrote", ModulesLoad)
		h.relabel(ModulesLoad)
	}
	// The keys appear with the module; the perimeter's table has loaded it
	// on a node that runs, a new one may not have it yet.
	_, _ = h.Run("modprobe", "nf_conntrack")
	live := map[string]uint64{}
	keys := []string{ConntrackMaxKey, ConntrackBucketsKey}
	for _, t := range conntrackTimes {
		keys = append(keys, t.key)
	}
	for _, key := range keys {
		out, err := h.Run("sysctl", "-n", key)
		if err != nil {
			continue
		}
		if v, err := strconv.ParseUint(strings.TrimSpace(string(out)), 10, 64); err == nil {
			live[key] = v
		}
	}
	if len(live) == 0 {
		fmt.Fprintln(h.Out, "warning: the conntrack keys cannot be read (no nf_conntrack?): the table's size and times stay the kernel's")
		return
	}
	mem := h.memTotal()
	size := ConntrackSize(mem)
	// Writing the live value back changes nothing, and tells whether the
	// size may change here at all (and the buckets on this kernel).
	writable := map[string]bool{}
	for _, key := range []string{ConntrackMaxKey, ConntrackBucketsKey} {
		if v, ok := live[key]; ok {
			writable[key] = h.run("sysctl", "-q", "-w", fmt.Sprintf("%s=%d", key, v)) == nil
		}
	}
	if !writable[ConntrackMaxKey] && live[ConntrackMaxKey] < size {
		fmt.Fprintf(h.Out, "warning: the conntrack table's size cannot be changed here (a container: only the host sets it): %s is %d, "+
			"raycontrol would set %d for %d MiB; one user can fill %d entries (spec/conn-limit-v1.md §1.2), and the guard refuses the "+
			"data plane's new connections from 85 %%\n", ConntrackMaxKey, live[ConntrackMaxKey], size, mem>>10, live[ConntrackMaxKey])
	}
	want := ConntrackKeys(size, live, h.fileKeys(ConntrackSysctl), writable)
	f := conntrackFile(want)
	changed, err = h.WriteFile(f)
	if err != nil {
		fmt.Fprintf(h.Out, "warning: %s cannot be written: %v\n", f.Path, err)
		return
	}
	if changed {
		fmt.Fprintln(h.Out, "wrote", f.Path)
		h.relabel(f.Path)
	}
	// Loaded when it changed, or when a value is not the file's (set again
	// by hand, or a boot that loaded the keys before the module).
	stale := false
	for _, k := range want {
		stale = stale || live[k.Key] != k.Value
	}
	if changed || stale {
		h.ApplySysctl([]File{f})
	}
}

// conntrackKey reports whether a sysctl key is one of ConntrackSysctl's.
func conntrackKey(key string) bool {
	if key == ConntrackMaxKey || key == ConntrackBucketsKey {
		return true
	}
	for _, t := range conntrackTimes {
		if t.key == key {
			return true
		}
	}
	return false
}
