// PortRange is a range of host ports clients reach. rayspa decides per
// address and port in its own table; host firewalls only have to let these
// ports through, since a packet must pass every base chain of the ruleset.
type PortRange struct {
	Proto    string // tcp | udp
	From, To uint16
}

func (r PortRange) String() string {
	if r.From == r.To {
		return fmt.Sprintf("%s/%d", r.Proto, r.From)
	}
	return fmt.Sprintf("%s/%d-%d", r.Proto, r.From, r.To)
}

// MergePorts sorts the ranges and joins overlapping or adjacent ones.
func MergePorts(in []PortRange) []PortRange {
	rs := slices.Clone(in)
	slices.SortFunc(rs, func(a, b PortRange) int {
		if c := strings.Compare(a.Proto, b.Proto); c != 0 {
			return c
		}
		return int(a.From) - int(b.From)
	})
	var out []PortRange
	for _, r := range rs {
		if n := len(out); n > 0 && out[n-1].Proto == r.Proto && int(r.From) <= int(out[n-1].To)+1 {
			out[n-1].To = max(out[n-1].To, r.To)
			continue
		}
		out = append(out, r)
	}
	return out
}

// Files that open the host ports in firewalld and ufw. They are written only
// where that firewall's configuration directory exists.
const (
	FirewalldService = "/etc/firewalld/services/raycontrol.xml"
	UFWProfile       = "/etc/ufw/applications.d/raycontrol"
	firewallName     = "raycontrol"
)

// firewallDirs maps a firewall file to the directory that must exist.
var firewallDirs = map[string]string{FirewalldService: "/etc/firewalld", UFWProfile: "/etc/ufw"}

// FirewallFiles returns the firewalld service and the ufw application
// profile for the host ports.
func FirewallFiles(ports []PortRange) []File {
	var fw, ufw strings.Builder
	fw.WriteString(`<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by raycontrol; changes are overwritten by rayctl apply. -->
<service>
  <short>raycontrol</short>
  <description>raycontrol node: SPA, public services and SSH. rayspa gates every port in its own nftables table.</description>
`)
	var parts []string
	for _, r := range ports {
		fmt.Fprintf(&fw, "  <port protocol=\"%s\" port=\"%d", r.Proto, r.From)
		part := strconv.Itoa(int(r.From))
		if r.To != r.From {
			fmt.Fprintf(&fw, "-%d", r.To)
			part += ":" + strconv.Itoa(int(r.To))
		}
		fw.WriteString("\"/>\n")
		parts = append(parts, part+"/"+r.Proto)
	}
	fw.WriteString("</service>\n")
	fmt.Fprintf(&ufw, "# Generated by raycontrol; changes are overwritten by rayctl apply.\n[%s]\ntitle=raycontrol node\n"+
		"description=SPA, public services and SSH; rayspa gates every port\nports=%s\n", firewallName, strings.Join(parts, "|"))
	return []File{
		{Path: FirewalldService, Mode: 0o644, Content: []byte(fw.String())},
		{Path: UFWProfile, Mode: 0o644, Content: []byte(ufw.String())},
	}
}

// skipFile reports whether a plan file is left out on this host: firewall
// files of firewalls that are not installed.
func (h *Host) skipFile(path string) bool {
	dir, ok := firewallDirs[path]
	if !ok {
		return false
	}
	_, err := os.Stat(h.path(dir))
	return err != nil
}

func (h *Host) lookPath(name string) bool {
	if h.LookPath == nil {
		return false
	}
	_, err := h.LookPath(name)
	return err == nil
}

// hostFirewalls lets the host ports through firewalld and ufw, and warns
// about other tables that drop incoming packets by default.
func (h *Host) hostFirewalls(plan Plan, changed map[string]bool) error {
	if len(plan.HostPorts) == 0 {
		return nil
	}
	handled := map[string]bool{}
	if !h.skipFile(FirewalldService) && h.lookPath("firewall-cmd") {
		if err := h.firewalld(changed[FirewalldService]); err != nil {
			return err
		}
		handled["firewalld"] = true
	}
	if !h.skipFile(UFWProfile) && h.lookPath("ufw") {
		active, err := h.ufw(changed[UFWProfile])
		if err != nil {
			return err
		}
		handled["ufw"] = active
	}
	if h.lookPath("nft") {
		h.warnDropChains(plan.HostPorts, handled)
	}
	return nil
}

// firewalld adds the raycontrol service to the default and every active
// zone. A stopped firewalld gets it in its permanent configuration.
func (h *Host) firewalld(changed bool) error {
	// Ask systemd, not firewall-cmd: with D-Bus down firewall-cmd fails while
	// firewalld still filters, and an offline change would never load.
	if _, err := h.Run("systemctl", "is-active", "--quiet", "firewalld.service"); err != nil {
		if !h.lookPath("firewall-offline-cmd") {
			return nil
		}
		if _, err := h.Run("firewall-offline-cmd", "--query-service="+firewallName); err == nil {
			return nil
		}
		if out, err := h.Run("firewall-offline-cmd", "--get-default-zone"); err == nil {
			if err := h.recordZone(strings.TrimSpace(string(out))); err != nil {
				return err
			}
		}
		fmt.Fprintln(h.Out, "firewalld (stopped): adding service", firewallName, "to the default zone")
		return h.run("firewall-offline-cmd", "--add-service="+firewallName)
	}
	if changed {
		// A new or changed service file is read on reload.
		if err := h.run("firewall-cmd", "--reload"); err != nil {
			return err
		}
	}
	zones := map[string]bool{}
	if out, err := h.Run("firewall-cmd", "--get-default-zone"); err == nil {
		if z := strings.TrimSpace(string(out)); z != "" {
			zones[z] = true
		}
	}
	if out, err := h.Run("firewall-cmd", "--get-active-zones"); err == nil {
		for _, line := range strings.Split(string(out), "\n") {
			// Zone names start the line; their interfaces and sources are indented.
			if line != "" && line[0] != ' ' && line[0] != '\t' {
				zones[strings.Fields(line)[0]] = true
			}
		}
	}
	names := slices.Sorted(func(yield func(string) bool) {
		for z := range zones {
			if !yield(z) {
				return
			}
		}
	})
	added := false
	for _, z := range names {
		if _, err := h.Run("firewall-cmd", "--permanent", "--zone="+z, "--query-service="+firewallName); err == nil {
			continue
		}
		if err := h.recordZone(z); err != nil {
			return err
		}
		if err := h.run("firewall-cmd", "--permanent", "--zone="+z, "--add-service="+firewallName); err != nil {
			return err
		}
		fmt.Fprintln(h.Out, "firewalld: service", firewallName, "added to zone", z)
		added = true
	}
	if added {
		return h.run("firewall-cmd", "--reload")
	}
	return nil
}

// recordZone notes the zone's files before firewalld rewrites them: the
// zone file in /etc and the backup firewalld keeps next to it.
func (h *Host) recordZone(zone string) error {
	if zone == "" || strings.ContainsAny(zone, "/.") {
		return nil
	}
	for _, f := range []string{"/etc/firewalld/zones/" + zone + ".xml", "/etc/firewalld/zones/" + zone + ".xml.old"} {
		if err := h.Journal.RecordFile(f); err != nil {
			return err
		}
	}
	return nil
}

// ufw allows the raycontrol application profile. Rules can be added while
// ufw is inactive, so the ports are there whenever it is enabled.
func (h *Host) ufw(changed bool) (active bool, err error) {
	out, _ := h.Run("ufw", "status")
	active = bytes.Contains(out, []byte("Status: active"))
	// ufw keeps its rules in these files; uninstall puts them back.
	for _, f := range []string{"/etc/ufw/user.rules", "/etc/ufw/user6.rules"} {
		if err := h.Journal.RecordFile(f); err != nil {
			return active, err
		}
	}
	if changed {
		// Refreshes an existing rule from the profile; harmless without one.
		_, _ = h.Run("ufw", "app", "update", firewallName)
	}
	if err := h.run("ufw", "allow", firewallName); err != nil {
		return active, err
	}
	return active, nil
}

// nftChain is a base chain as nft -j list chains gives it.
type nftChain struct {
	Family string `json:"family"`
	Table  string `json:"table"`
	Name   string `json:"name"`
	Hook   string `json:"hook"`
	Policy string `json:"policy"`
}

// dropChains are the base chains of other tables on a hook that drop by
// default; nil when nft cannot tell.
func (h *Host) dropChains(hook string) []nftChain {
	out, err := h.Run("nft", "-j", "list", "chains")
	if err != nil {
		return nil
	}
	var ruleset struct {
		Nftables []struct {
			Chain *nftChain `json:"chain"`
		} `json:"nftables"`
	}
	if json.Unmarshal(out, &ruleset) != nil {
		return nil
	}
	var drop []nftChain
	for _, e := range ruleset.Nftables {
		if c := e.Chain; c != nil && c.Hook == hook && c.Policy == "drop" && c.Table != rayspaTable {
			drop = append(drop, *c)
		}
	}
	return drop
}

// warnDropChains warns about input chains of other tables that drop by
// default: rayspa cannot open ports there, so the operator must.
func (h *Host) warnDropChains(ports []PortRange, handled map[string]bool) {
	var list []string
	for _, p := range ports {
		list = append(list, p.String())
	}
	for _, c := range h.dropChains("input") {
		if c.Table == "firewalld" && handled["firewalld"] {
			continue
		}
		// ufw runs on iptables-nft: tables "filter", chain INPUT.
		if c.Table == "filter" && c.Name == "INPUT" && handled["ufw"] {
			continue
		}
		fmt.Fprintf(h.Out, "warning: nftables chain %s %s %s drops incoming packets by default; "+
			"it must accept %s, or clients cannot reach the node\n", c.Family, c.Table, c.Name, strings.Join(list, " "))
	}
}

// WarnRelayDropChains warns, on a relay host, about chains of other tables
// (ufw, firewalld) that drop by default what the relay needs: the
// forwarded packets, and its probe endpoint's port (0: none).
func (h *Host) WarnRelayDropChains(probePort uint16) {
	for _, c := range h.dropChains("forward") {
		fmt.Fprintf(h.Out, "warning: nftables chain %s %s %s drops forwarded packets by default: the relay forwards "+
			"nothing to the exit until it accepts them (ufw: DEFAULT_FORWARD_POLICY=\"ACCEPT\" in /etc/default/ufw)\n",
			c.Family, c.Table, c.Name)
	}
	if probePort == 0 {
		return
	}
	for _, c := range h.dropChains("input") {
		fmt.Fprintf(h.Out, "warning: nftables chain %s %s %s drops incoming packets by default: it must accept "+
			"tcp/%d and udp/%d, the relay's probe endpoint (ufw allow %d)\n", c.Family, c.Table, c.Name, probePort, probePort, probePort)
	}
}

// rayspaTable is perimeter.Table.
const rayspaTable = "raycontrol"

// warnPort53 warns when another process holds UDP port 53 that the front
// needs for the DNS tunnels.
func (h *Host) warnPort53(frontUID int) {
	for _, o := range h.OthersOn53(frontUID) {
		fmt.Fprintf(h.Out, "warning: UDP port 53 (%s) is taken by %s (another DNS server?); "+
			"the DNS tunnels' queries there do not reach the front\n", o.Addr, o.Owner)
	}
}

// Holder53 is a socket on UDP port 53 that is not the front's.
type Holder53 struct{ Addr, Owner string }

// OthersOn53 lists the sockets on UDP port 53 other than the front's and
// systemd-resolved's stub (127.0.0.53, 127.0.0.54), which shares the port
// with the front: both bind with SO_REUSEADDR (niko-server v0.8.2). Another
// such socket takes the datagrams to its own address, quietly; one without
// it keeps the front from starting.
func (h *Host) OthersOn53(frontUID int) []Holder53 {
	var out []Holder53
	for _, l := range h.port53() {
		if l.uid == frontUID || l.addr == "127.0.0.53" || l.addr == "127.0.0.54" {
			continue
		}
		owner := "uid " + strconv.Itoa(l.uid)
		if u, err := user.LookupId(strconv.Itoa(l.uid)); err == nil {
			owner = "user " + u.Username
		}
		out = append(out, Holder53{l.addr, owner})
	}
	return out
}

// stubOn53 reports whether systemd-resolved's stub holds 127.0.0.53:53.
func (h *Host) stubOn53() bool {
	return slices.ContainsFunc(h.port53(), func(l udpListener) bool { return l.addr == "127.0.0.53" })
}

type udpListener struct {
	addr string
	uid  int
}

// port53 lists the sockets bound to UDP port 53.
func (h *Host) port53() []udpListener {
	var out []udpListener
	for _, f := range []string{"/proc/net/udp", "/proc/net/udp6"} {
		data, err := os.ReadFile(h.path(f)) //nolint:gosec // G304: fixed paths
		if err != nil {
			continue
		}
		sc := bufio.NewScanner(bytes.NewReader(data))
		sc.Scan() // header
		for sc.Scan() {
			fields := strings.Fields(sc.Text())
			if len(fields) < 8 {
				continue
			}
			addr, port, ok := strings.Cut(fields[1], ":")
			if !ok || port != "0035" {
				continue
			}
			uid, err := strconv.Atoi(fields[7])
			if err != nil {
				continue
			}
			out = append(out, udpListener{hexAddr(addr), uid})
		}
	}
	return out
}

// hexAddr formats an address from /proc/net/udp{,6}: 32-bit words in host
// (little-endian) order.
func hexAddr(s string) string {
	b := make([]byte, 0, 16)
	for i := 0; i+8 <= len(s); i += 8 {
		w, err := strconv.ParseUint(s[i:i+8], 16, 32)
		if err != nil {
			return s
		}
		b = binary.LittleEndian.AppendUint32(b, uint32(w))
	}
	if a, ok := netip.AddrFromSlice(b); ok {
		return a.Unmap().String()
	}
	return s
}
