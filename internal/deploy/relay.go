package deploy

import (
	"path"

	"github.com/arngory/raycontrol/internal/render"
)

// RelayBundle is where a relay host keeps its bundle (rayctl relay bundle
// on the exit): root's, 0600; it holds the relay's private key.
const RelayBundle = "/etc/raycontrol/relay.bundle"

// relayBundleCopy is rayspa's copy of it, put there by root at each start,
// readable by rayspa only (as the DNS tunnels' keys, R2-9).
const relayBundleCopy = "/run/rayspa/relay.bundle"

// RelayProbeUnit is rayd relay's unit on a relay host: the relay's probe
// endpoint (relay-v1 §9.1).
const RelayProbeUnit = "rayd-relay.service"

// relaySysctl turns forwarding on, in the relay role only (relay-v1 §3.1);
// IPv4: the exit is one IPv4 address.
const relaySysctl = "# Generated by raycontrol: this host is a relay (spec/relay-v1.md §3.1).\nnet.ipv4.ip_forward = 1\n"

// RelayProbeState is where rayd relay keeps the devices of its last
// snapshot.
const RelayProbeState = "/var/lib/rayd-relay/devices.json"

// relayProbeBundleCopy is rayd relay's copy of the bundle, as rayspa's.
const relayProbeBundleCopy = "/run/rayd-relay/relay.bundle"

// RelayPlan is a relay host (spec/relay-v1.md §3.1): rayspa alone, taking its
// perimeter from the exit and forwarding the services to it in the kernel.
// No rayd, no data plane, nothing listens: the host forwards and knocks are
// answered by nftables.
func RelayPlan(bin Binaries) Plan {
	u := unit{
		name:        "rayspa.service",
		description: "raycontrol relay (nftables, SPA v2, forwarding to the exit)",
		after:       []string{"nftables.service", "firewalld.service", "ufw.service"},
		service: []string{
			"User=rayspa", "Group=rayspa",
			"RuntimeDirectory=rayspa", "RuntimeDirectoryMode=0700",
			copyIn(bin.Rayd, path.Dir(RelayBundle), bundleOwner, "rayspa", RelayBundle, relayBundleCopy),
			"ExecStart=" + bin.Rayspa + " run -relay " + relayBundleCopy + " -state " + RayspaState,
			// The last snapshot: the relay's SPA keys and the admin addresses.
			"StateDirectory=rayspa", "StateDirectoryMode=0700",
			"AmbientCapabilities=CAP_NET_ADMIN",
			"CapabilityBoundingSet=CAP_NET_ADMIN",
			"RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK",
		},
	}
	// The relay's probe endpoint (relay-v1 §9.1): no privileges, a port
	// above 1024, its own copy of the bundle. It runs only beside rayspa:
	// rayspa stopped (a failed install, the guard, by hand) stops it, and
	// it does not start without rayspa, so the exit never lists an
	// endpoint on a relay that forwards nothing; and rayspa's start pulls
	// it in (enabled, it is wanted by rayspa), so it comes back with it.
	probe := unit{
		name:        RelayProbeUnit,
		description: "raycontrol relay probe endpoint (relay-v1 §9.1)",
		after:       []string{u.name},
		unitLines:   []string{"PartOf=" + u.name, "Requisite=" + u.name},
		wantedBy:    u.name,
		service: []string{
			"User=rayd", "Group=rayd",
			"RuntimeDirectory=rayd-relay", "RuntimeDirectoryMode=0700",
			copyIn(bin.Rayd, path.Dir(RelayBundle), bundleOwner, "rayd", RelayBundle, relayProbeBundleCopy),
			"ExecStart=" + bin.Rayd + " relay -bundle " + relayProbeBundleCopy + " -state " + RelayProbeState,
			// The devices of the last snapshot, for a start while the exit
			// is away (their K_relay: rayd's only).
			"StateDirectory=rayd-relay", "StateDirectoryMode=0700",
			"CapabilityBoundingSet=",
			"RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6",
		},
	}
	return Plan{
		Users: []SystemUser{{Name: "rayspa", UID: render.RayspaUID}, {Name: "rayd", UID: render.RaydUID}},
		Files: []File{
			u.file(),
			probe.file(),
			{Path: HardeningSysctl, Mode: 0o644, Content: []byte(sysctl)},
			{Path: RelaySysctl, Mode: 0o644, Content: []byte(relaySysctl)},
		},
		Units: []string{u.name, probe.name},
	}
}
