package deploy

import (
	"path"

	"github.com/arngory/raycontrol/internal/nodeupdate"
	"github.com/arngory/raycontrol/internal/render"
)

// RelayBundle is where a relay host keeps its bundle (rayctl relay bundle
// on the exit): root's, 0600; it holds the relay's private key.
const RelayBundle = "/etc/raycontrol/relay.bundle"

// relayBundleCopy is rayspa's copy of it, put there by root at each start,
// readable by rayspa only (as the DNS tunnels' keys, R2-9).
const relayBundleCopy = "/run/rayspa/relay.bundle"

// RelayProbeUnit is rayd relay's unit on a relay host: the relay's probe
// endpoint (relay-v1 §9.1).
const RelayProbeUnit = "rayd-relay.service"

// relaySysctl turns forwarding on, in the relay role only (relay-v1 §3.1);
// IPv4: the exit is one IPv4 address.
const relaySysctl = "# Generated by raycontrol: this host is a relay (spec/relay-v1.md §3.1).\nnet.ipv4.ip_forward = 1\n"

// RelayProbeState is where rayd relay keeps the devices of its last
// snapshot.
const RelayProbeState = "/var/lib/rayd-relay/devices.json"

// relayProbeBundleCopy is rayd relay's copy of the bundle, as rayspa's.
const relayProbeBundleCopy = "/run/rayd-relay/relay.bundle"

// The relay's update by its exit's word (spec/relay-update-remote-v1.md
// §4.1): names of their own, not the node's, whose path unit watches
// another file. The path unit and the recover unit are enabled only while
// root's policy has remote on (rayctl update remote, rayctl install
// -relay); the update service is started by the path unit alone.
const (
	RelayUpdatePath    = "raycontrol-relay-update.path"
	RelayUpdateService = "raycontrol-relay-update.service"
	RelayRecover       = "raycontrol-relay-recover.service"
	// RelayUpdateMark is the mark of an update of the relay that did not
	// end (rayctl's relay.unfinished, in the copy an update keeps).
	RelayUpdateMark = JournalDir + "/previous/relay.unfinished"
)

// relayUpdatePath sees the request rayd relay writes in its own state
// directory, for root to check and run.
const relayUpdatePath = `# Generated by raycontrol; changes are overwritten by rayctl install -relay.
[Unit]
Description=raycontrol: an update the relay's exit named (spec/relay-update-remote-v1.md)

[Path]
PathExists=` + nodeupdate.RelayRequestFile + `

[Install]
WantedBy=multi-user.target
`

// relayUpdateService runs the request as root: rayctl update -request
// checks it again (root's policy, signed releases only, strictly newer)
// and updates the relay as by hand. No sandbox: it installs the relay.
// After the recover unit: an update that did not end is rolled back
// before another begins. The stop's SIGTERM reaches the update, which
// rolls the relay back within TimeoutStopSec; a runner killed on the way
// is ended by ExecStopPost.
const relayUpdateService = `# Generated by raycontrol; changes are overwritten by rayctl install -relay.
[Unit]
Description=raycontrol relay update by the exit's word (rayctl update -request)
Wants=network-online.target
After=network-online.target rayspa.service ` + RelayRecover + `

[Service]
Type=oneshot
ExecStart=/usr/local/bin/rayctl update -request
ExecStopPost=-/usr/local/bin/rayctl update -request-ended
TimeoutStartSec=15min
TimeoutStopSec=5min
StateDirectory=raycontrol-update
StateDirectoryMode=0755
`

// relayRecover rolls back, once a boot, an update by the exit's word that
// a shutdown or a power cut ended halfway (the mark is there); one by
// hand it leaves to the person who ran it.
const relayRecover = `# Generated by raycontrol; changes are overwritten by rayctl install -relay.
[Unit]
Description=raycontrol: roll back an update of the relay that did not end (rayctl update -request-recover)
ConditionPathExists=` + RelayUpdateMark + `
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/bin/rayctl update -request-recover
TimeoutStartSec=10min

[Install]
WantedBy=multi-user.target
`

// RelayPlan is a relay host (spec/relay-v1.md §3.1): rayspa alone, taking its
// perimeter from the exit and forwarding the services to it in the kernel.
// No rayd, no data plane, nothing listens: the host forwards and knocks are
// answered by nftables.
func RelayPlan(bin Binaries) Plan {
	u := unit{
		name:        "rayspa.service",
		description: "raycontrol relay (nftables, SPA v2, forwarding to the exit)",
		// Before the interfaces come up, as on a node (R4-40): forwarding
		// is on from sysctl.d by then, and the relay's table, or until its
		// first snapshot a forward chain that drops (HoldForward), is in.
		early: true,
		after: rayspaAfter,
		service: append([]string{
			"User=rayspa", "Group=rayspa",
			"RuntimeDirectory=rayspa", "RuntimeDirectoryMode=0700",
			copyIn(bin.Rayd, path.Dir(RelayBundle), bundleOwner, "rayspa", RelayBundle, relayBundleCopy),
			"ExecStart=" + bin.Rayspa + " run -relay " + relayBundleCopy + " -state " + RayspaState,
			// The last snapshot: the relay's SPA keys and the admin addresses.
			"StateDirectory=rayspa", "StateDirectoryMode=0700",
			"AmbientCapabilities=CAP_NET_ADMIN",
			"CapabilityBoundingSet=CAP_NET_ADMIN",
			"RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK",
		}, rayspaReady...),
	}
	// The relay's probe endpoint (relay-v1 §9.1): no privileges, a port
	// above 1024, its own copy of the bundle. It runs only beside rayspa:
	// rayspa stopped (a failed install, the guard, by hand) stops it, and
	// it does not start without rayspa, so the exit never lists an
	// endpoint on a relay that forwards nothing; and rayspa's start pulls
	// it in (enabled, it is wanted by rayspa), so it comes back with it.
	probe := unit{
		name:        RelayProbeUnit,
		description: "raycontrol relay probe endpoint (relay-v1 §9.1)",
		after:       []string{u.name},
		unitLines:   []string{"PartOf=" + u.name, "Requisite=" + u.name},
		wantedBy:    u.name,
		service: []string{
			"User=rayd", "Group=rayd",
			"RuntimeDirectory=rayd-relay", "RuntimeDirectoryMode=0700",
			copyIn(bin.Rayd, path.Dir(RelayBundle), bundleOwner, "rayd", RelayBundle, relayProbeBundleCopy),
			"ExecStart=" + bin.Rayd + " relay -bundle " + relayProbeBundleCopy + " -state " + RelayProbeState,
			// The devices of the last snapshot, for a start while the exit
			// is away (their K_relay: rayd's only).
			"StateDirectory=rayd-relay", "StateDirectoryMode=0700",
			"CapabilityBoundingSet=",
			"RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6",
		},
	}
	return Plan{
		Users: []SystemUser{{Name: "rayspa", UID: render.RayspaUID}, {Name: "rayd", UID: render.RaydUID}},
		Files: []File{
			u.file(),
			probe.file(),
			{Path: HardeningSysctl, Mode: 0o644, Content: []byte(sysctl)},
			{Path: RelaySysctl, Mode: 0o644, Content: []byte(relaySysctl)},
			// The update by the exit's word: files only, none of Units;
			// enabled as root's policy has it (rayctl install -relay).
			{Path: "/etc/systemd/system/" + RelayUpdatePath, Mode: 0o644, Content: []byte(relayUpdatePath)},
			{Path: "/etc/systemd/system/" + RelayUpdateService, Mode: 0o644, Content: []byte(relayUpdateService)},
			{Path: "/etc/systemd/system/" + RelayRecover, Mode: 0o644, Content: []byte(relayRecover)},
		},
		Units: []string{u.name, probe.name},
	}
}
