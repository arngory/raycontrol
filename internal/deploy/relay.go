package deploy

import (
	"github.com/arngory/raycontrol/internal/render"
)

// RelayBundle is where a relay host keeps its bundle (rayctl relay bundle
// on the exit): root's, 0600; it holds the relay's private key.
const RelayBundle = "/etc/raycontrol/relay.bundle"

// relayBundleCopy is rayspa's copy of it, put there by root at each start,
// readable by rayspa only (as the DNS tunnels' keys, R2-9).
const relayBundleCopy = "/run/rayspa/relay.bundle"

// RelayPlan is a relay host (spec/relay-v1.md §3.1): rayspa alone, taking its
// perimeter from the exit and forwarding the services to it in the kernel.
// No rayd, no data plane, nothing listens: the host forwards and knocks are
// answered by nftables.
func RelayPlan(bin Binaries) Plan {
	u := unit{
		name:        "rayspa.service",
		description: "raycontrol relay (nftables, SPA v2, forwarding to the exit)",
		after:       []string{"nftables.service", "firewalld.service", "ufw.service"},
		service: []string{
			"User=rayspa", "Group=rayspa",
			"RuntimeDirectory=rayspa", "RuntimeDirectoryMode=0700",
			"ExecStartPre=+install -m 0400 -o rayspa -g rayspa " + RelayBundle + " " + relayBundleCopy,
			"ExecStart=" + bin.Rayspa + " run -relay " + relayBundleCopy + " -state " + RayspaState,
			// The last snapshot: the relay's SPA keys and the admin addresses.
			"StateDirectory=rayspa", "StateDirectoryMode=0700",
			"AmbientCapabilities=CAP_NET_ADMIN",
			"CapabilityBoundingSet=CAP_NET_ADMIN",
			"RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK",
		},
	}
	return Plan{
		Users: []SystemUser{{Name: "rayspa", UID: render.RayspaUID}},
		Files: []File{
			u.file(),
			{Path: "/etc/sysctl.d/90-raycontrol.conf", Mode: 0o644, Content: []byte(sysctl)},
			// Forwarding only in the relay role (relay-v1 §3.1); IPv4: the
			// exit is one IPv4 address.
			{Path: RelaySysctl, Mode: 0o644, Content: []byte(
				"# Generated by raycontrol: this host is a relay (spec/relay-v1.md §3.1).\nnet.ipv4.ip_forward = 1\n")},
		},
		Units: []string{u.name},
	}
}
