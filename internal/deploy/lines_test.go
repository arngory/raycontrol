package deploy

import (
	"strings"
	"testing"
)

// Step 2 of spec/apply-plan-v1.md §4.1, apart from CheckService, which
// keeps such values from reaching it: a value that would break a unit's
// or tmpfiles' lines leaves the unit or the line out.
func TestLinesUnbroken(t *testing.T) {
	good := unit{name: "niko-x.service", description: "x y", needs: "/var/lib/raycontrol/rendered/x/a",
		after: []string{"niko-y.service"}, service: []string{"User=niko-x", "ExecStart=/usr/local/bin/rayd site -answer 404", "ReadWritePaths=/run/niko/x-in"}}
	if err := good.check(); err != nil {
		t.Fatal(err)
	}
	for name, f := range map[string]func(*unit){
		"name with a line":          func(u *unit) { u.name = "niko-x.service\nExecStartPre=+/bin/sh" },
		"name with a space":         func(u *unit) { u.name = "niko-x .service" },
		"description with a line":   func(u *unit) { u.description = "x\nUser=root" },
		"description with a return": func(u *unit) { u.description = "x\rUser=root" },
		"needs with a space":        func(u *unit) { u.needs = "/var/lib/a b" },
		"after with a line":         func(u *unit) { u.after = []string{"a\nb"} },
		"a value with a line": func(u *unit) {
			u.service[1] = "ExecStart=/usr/local/bin/rayd site -answer 404\nExecStartPre=+/bin/sh -c id"
		},
		"a path with a space":  func(u *unit) { u.service[2] = "ReadWritePaths=/run/niko/x-in /etc" },
		"a user with a space":  func(u *unit) { u.service[0] = "User=niko-x root" },
		"a line without a key": func(u *unit) { u.service = append(u.service, "[Service]") },
	} {
		u := good
		u.after, u.service = append([]string(nil), good.after...), append([]string(nil), good.service...)
		f(&u)
		if err := u.check(); err == nil {
			t.Errorf("%s: accepted", name)
		}
	}

	var tmp tmpfiles
	tmp.dir("/run/niko", "0755", "root", "root")
	tmp.dir("/run/niko/x 0755 root root -\nZ /etc", "2750", "rayd", "niko-front")
	tmp.dir("/run/niko/y", "2750", "rayd", "niko-front\nZ /etc 0777 rayd rayd -")
	tmp.dir("/run/niko/z", "2750", "niko-z", "niko-front")
	if s := tmp.String(); strings.Contains(s, "Z /etc") || len(tmp.warnings) != 2 || len(tmp.dirs) != 2 ||
		s != "# Generated by raycontrol.\nd /run/niko 0755 root root -\nd /run/niko/z 2750 niko-z niko-front -\n" {
		t.Errorf("tmpfiles:\n%s\nwarnings %q", s, tmp.warnings)
	}
}
